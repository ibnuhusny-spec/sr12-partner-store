// Helper: Rotasi Produk Harian (Deterministik Berdasarkan Tanggal Kalender)
function getDailyRotatedProducts(products) {
  if (!Array.isArray(products) || products.length === 0) return [];
  const today = new Date();
  // Seed unik per hari: YYYYMMDD (contoh: 20261011)
  const seed = (today.getFullYear() * 10000) + ((today.getMonth() + 1) * 100) + today.getDate();
  const list = [...products];

  // Pseudo Random Number Generator deterministik
  let s = seed;
  function nextRand() {
    s = (s * 9301 + 49297) % 233280;
    return s / 233280;
  }

  // Permutasi Fisher-Yates per tanggal
  for (let i = list.length - 1; i > 0; i--) {
    const j = Math.floor(nextRand() * (i + 1));
    const temp = list[i];
    list[i] = list[j];
    list[j] = temp;
  }

  return list;
}

