function makeCategoryIllustration(category: string, icon: string, name: string, netto: string): string {
  // Curated color themes per category
  let c1 = '#064e3b';
  let c2 = '#047857';
  let tagColor = '#a7f3d0';

  if (category === 'Acne Series') {
    c1 = '#831843'; c2 = '#be185d'; tagColor = '#fbcfe8';
  } else if (category === 'Face Mask' || category === 'Face Care') {
    c1 = '#701a75'; c2 = '#a21caf'; tagColor = '#f5d0fe';
  } else if (category === 'Face Wash') {
    c1 = '#0e7490'; c2 = '#0891b2'; tagColor = '#cffafe';
  } else if (category === 'SR Kiddos') {
    c1 = '#b45309'; c2 = '#d97706'; tagColor = '#fef3c7';
  } else if (category === 'Toothpaste') {
    c1 = '#334155'; c2 = '#475569'; tagColor = '#e2e8f0';
  } else if (category === 'Parfum') {
    c1 = '#4c1d95'; c2 = '#6d28d9'; tagColor = '#ede9fe';
  } else if (category === 'Hair Care') {
    c1 = '#1e3a8a'; c2 = '#1d4ed8'; tagColor = '#dbeafe';
  } else if (category === 'Body Care') {
    c1 = '#065f46'; c2 = '#059669'; tagColor = '#a7f3d0';
  } else if (category === 'Personal Care') {
    c1 = '#9d174d'; c2 = '#db2777'; tagColor = '#fce7f3';
  } else if (category === 'Skinsane') {
    c1 = '#854d0e'; c2 = '#ca8a04'; tagColor = '#fef08a';
  } else if (category === 'Herbal') {
    c1 = '#14532d'; c2 = '#16a34a'; tagColor = '#bbf7d0';
  } else if (category === 'Beauty Drink') {
    c1 = '#831843'; c2 = '#e11d48'; tagColor = '#ffe4e6';
  }

  const shortName = name.length > 24 ? name.substring(0, 22) + '..' : name;

  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="400" height="300" viewBox="0 0 400 300">
    <defs>
      <linearGradient id="g_${category.replace(/\s+/g, '_')}" x1="0%" y1="0%" x2="100%" y2="100%">
        <stop offset="0%" stop-color="${c1}"/>
        <stop offset="100%" stop-color="${c2}"/>
      </linearGradient>
    </defs>
    <rect width="400" height="300" fill="url(#g_${category.replace(/\s+/g, '_')})"/>
    <circle cx="200" cy="115" r="70" fill="rgba(255,255,255,0.12)" stroke="rgba(255,255,255,0.25)" stroke-width="2"/>
    <text x="200" y="132" font-size="62" text-anchor="middle" dominant-baseline="middle">${icon}</text>
    <rect x="30" y="205" width="340" height="68" rx="10" fill="rgba(0,0,0,0.38)" stroke="rgba(255,255,255,0.18)"/>
    <text x="200" y="232" font-family="'Plus Jakarta Sans', Arial, sans-serif" font-weight="800" font-size="15" fill="#ffffff" text-anchor="middle">${shortName}</text>
    <text x="200" y="254" font-family="'Plus Jakarta Sans', Arial, sans-serif" font-weight="600" font-size="12" fill="${tagColor}" text-anchor="middle">SR12 ${category} • ${netto}</text>
  </svg>`;
  return 'data:image/svg+xml;charset=utf-8,' + encodeURIComponent(svg);
}

